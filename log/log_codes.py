"""프로젝트 공통 로그 코드 번호 정의."""

from __future__ import annotations

from enum import IntEnum


class LogCode(IntEnum):
    """기능별 로그 코드.

    1xxx는 Ollama, 2xxx는 Keyword, 3xxx는 논문 검색,
    4xxx는 검색 논문 저장, 5xxx는 논문 추출·파싱,
    6xxx는 번역, 7xxx는 요약, 8xxx는 Vector DB 저장,
    9xxx는 Deep Research를 나타낸다.
    x1xx는 시작·상태, x2xx는 성공, x4xx는 입력 거부, x5xx는 오류다.
    """

    # 1xxx: Ollama 연결, 설정 및 텍스트 생성
    OLLAMA_CONNECTION_CHECKED = 1100
    OLLAMA_GENERATION_SUCCEEDED = 1200
    OLLAMA_CONNECTION_FAILED = 1500
    OLLAMA_GENERATION_FAILED = 1501
    OLLAMA_CONFIG_LOAD_FAILED = 1502

    # 2xxx: 사용자 질의로부터 학술 검색 키워드 생성
    KEYWORD_GENERATION_STARTED = 2100
    KEYWORD_GENERATION_SUCCEEDED = 2200
    KEYWORD_GENERATION_FALLBACK = 2300
    KEYWORD_GENERATION_REJECTED = 2400
    KEYWORD_GENERATION_FAILED = 2500

    # 3xxx: arXiv 등 외부 논문 검색 기능용
    PAPER_SEARCH_STARTED = 3100
    PAPER_SEARCH_SUCCEEDED = 3200
    PAPER_SEARCH_REJECTED = 3400
    PAPER_SEARCH_FAILED = 3500

    # 4xxx: 검색된 논문의 메타데이터·원문 저장 기능용
    PAPER_SAVE_STARTED = 4100
    PAPER_SAVE_SUCCEEDED = 4200
    PAPER_SAVE_REJECTED = 4400
    PAPER_SAVE_FAILED = 4500
    
    # 5xxx: PDF/원문 추출 및 마크다운 파싱
    PAPER_EXTRACTION_STARTED = 5100
    PAPER_EXTRACTION_SKIPPED = 5101
    PAPER_EXTRACTION_SUCCEEDED = 5200
    PAPER_EXTRACTION_REJECTED = 5400
    PAPER_EXTRACTION_FAILED = 5500
    PAGE_VISION_FALLBACK = 5401
    PAGE_VISION_UNAVAILABLE = 5402
    SECTION_CLASSIFY_FALLBACK = 5403

    # 6xxx: 논문 마크다운 번역, 재시도 및 임시 체크포인트
    TRANSLATION_STARTED = 6100
    TRANSLATION_CHUNK_STARTED = 6101
    TRANSLATION_RESUMED = 6102
    TRANSLATION_RETRYING = 6103
    TRANSLATION_CHUNK_SPLIT = 6104
    TRANSLATION_TABLE_PRESERVED = 6105
    TRANSLATION_SUCCEEDED = 6200
    TRANSLATION_CHECKPOINT_SAVED = 6201
    TRANSLATION_CHECKPOINT_DELETED = 6202
    TRANSLATION_MARKDOWN_SAVED = 6203
    TRANSLATION_REJECTED = 6400
    TRANSLATION_CHECKPOINT_INVALID = 6401
    TRANSLATION_FAILED = 6500
    TRANSLATION_CHECKPOINT_FAILED = 6501
    TRANSLATION_MARKDOWN_SAVE_FAILED = 6502

    # 7xxx: 번역된 논문의 청크 요약, 체크포인트 및 4단 구조 통합
    SUMMARY_STARTED = 7100
    SUMMARY_CHUNK_STARTED = 7101
    SUMMARY_RESUMED = 7102
    SUMMARY_RETRYING = 7103
    SUMMARY_REDUCE_STARTED = 7104
    SUMMARY_SUCCEEDED = 7200
    SUMMARY_MARKDOWN_SAVED = 7201
    SUMMARY_CHECKPOINT_SAVED = 7202
    SUMMARY_CHECKPOINT_DELETED = 7203
    SUMMARY_REJECTED = 7400
    SUMMARY_CHECKPOINT_INVALID = 7401
    SUMMARY_FAILED = 7500
    SUMMARY_MARKDOWN_SAVE_FAILED = 7501
    SUMMARY_CHECKPOINT_FAILED = 7502

    # 8xxx: 요약 임베딩 및 Chroma Vector DB 저장
    SUMMARY_STORAGE_STARTED = 8100
    SUMMARY_STORAGE_SUCCEEDED = 8200
    SUMMARY_STORAGE_FAILED = 8500

    # 9xxx: Deep Research 논문 선택·질의응답·관련 논문 검색
    DEEP_RESEARCH_LIST_STARTED = 9100
    DEEP_RESEARCH_ANSWER_STARTED = 9101
    DEEP_RESEARCH_RELATED_SEARCH_STARTED = 9102
    DEEP_RESEARCH_LIST_SUCCEEDED = 9200
    DEEP_RESEARCH_PAPER_SELECTED = 9201
    DEEP_RESEARCH_ANSWER_SUCCEEDED = 9202
    DEEP_RESEARCH_RELATED_SEARCH_SUCCEEDED = 9203
    DEEP_RESEARCH_REQUEST_REJECTED = 9400
    DEEP_RESEARCH_ANSWER_FAILED = 9500
    DEEP_RESEARCH_RELATED_SEARCH_FAILED = 9501
